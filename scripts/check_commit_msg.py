"""Conventional Commits check for commit messages and PR titles. Local only; no network.

Usage:
  python scripts/check_commit_msg.py .git/COMMIT_EDITMSG   # commit-msg hook (message file)
  python scripts/check_commit_msg.py --title "feat(cli): add explain"   # PR title (CI)

Rules: ``<type>(<optional scope>)<optional !>: <summary>``; type from ``TYPES``; summary 1-72
characters, no trailing period; a blank line between subject and body. Merge/revert/fixup
subjects generated by git are accepted. Exit 0 valid, 1 invalid, 2 usage error.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TYPES = (
    "feat",
    "fix",
    "security",
    "perf",
    "refactor",
    "test",
    "docs",
    "build",
    "ci",
    "chore",
    "revert",
)
SUBJECT_RE = re.compile(
    r"^(?P<type>" + "|".join(TYPES) + r")(?:\((?P<scope>[a-z0-9][a-z0-9._/-]{0,30})\))?(?P<bang>!)?"
    r": (?P<summary>\S.*)$"
)
GENERATED_RE = re.compile(r"^(Merge |Revert \"|fixup! |squash! |amend! )")
MAX_SUMMARY = 72


def problems_for(message: str) -> list[str]:
    lines = [ln for ln in message.splitlines() if not ln.startswith("#")]
    while lines and not lines[0].strip():
        lines.pop(0)
    if not lines:
        return ["empty commit message"]
    subject = lines[0].rstrip()
    if GENERATED_RE.match(subject):
        return []
    match = SUBJECT_RE.match(subject)
    if match is None:
        return [
            "subject must look like '<type>(<scope>): <summary>' with type one of: "
            + ", ".join(TYPES)
        ]
    found: list[str] = []
    summary = match.group("summary")
    if len(summary) > MAX_SUMMARY:
        found.append(f"summary is longer than {MAX_SUMMARY} characters")
    if summary.endswith("."):
        found.append("summary must not end with a period")
    if len(lines) > 1 and lines[1].strip():
        found.append("leave a blank line between the subject and the body")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Check a Conventional Commits message.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("message_file", nargs="?", help="path to the commit message file")
    group.add_argument("--title", help="check a single subject line (e.g. a PR title)")
    args = parser.parse_args(argv)
    if args.title is not None:
        message = args.title
    else:
        try:
            message = Path(args.message_file).read_text(encoding="utf-8")
        except OSError:
            print("commit-msg: cannot read the commit message file")
            return 2
    found = problems_for(message)
    if found:
        print("commit-msg: invalid message (see .claude/skills/git-workflow/SKILL.md):")
        for problem in found:
            print(f"  - {problem}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
